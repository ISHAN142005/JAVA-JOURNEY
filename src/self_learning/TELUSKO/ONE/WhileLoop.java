package self_learning.TELUSKO.ONE;

public class WhileLoop {
    public static void main(String[]main){
        //Nested while loop
        int i =1;
        while(i<=7){
            System.out.println("Day:"+i);
            int j=1;
            while(j<=24){
                System.out.println("Hour:"+j);
            j++;
            }
        i++;
        }
    }
}
