package self_learning.TELUSKO.ONE;

public class Literals {
    public static void main(String[] args) {
        //Literals

        int n1 = 0b101;  //5
        int n2 = 0x101;  //257
        int n3 = 0x7E;   //126
        int n4 = 10_00_000_000;  //1000000000
        double n5 = 12e10;
        float n6 = 56;
        char c = 'a';
        c++;
        System.out.println(n1 + "\n" + n2 + "\n" + n3 + "\n" + n4 );
        System.out.println(c);
    }
}
